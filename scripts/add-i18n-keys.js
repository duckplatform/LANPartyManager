/** Fusionne récursivement newKeys dans obj (sans écraser les clés existantes) */
function mergeDeep(obj, newKeys) {
  for (const [key, value] of Object.entries(newKeys)) {
    if (typeof value === 'object' && value !== null && !Array.isArray(value)) {
      if (!obj[key] || typeof obj[key] !== 'object') obj[key] = {};
      mergeDeep(obj[key], value);
    } else if (!(key in obj)) {
      obj[key] = value;
    }
  }
}

function processFile(filePath, newKeys) {
  const raw = fs.readFileSync(filePath, 'utf8');
  const data = JSON.parse(raw);
  mergeDeep(data, newKeys);
  fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + '\n', 'utf8');
  console.log(`✅ ${filePath} mis à jour`);
}

